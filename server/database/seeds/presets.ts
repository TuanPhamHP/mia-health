type PresetParams = Pick<CreateExerciseData, 'sets' | 'reps' | 'holdSec' | 'relaxSec' | 'durationSec' | 'restSec'>;

/** Trỏ tới bài bằng TÊN (id chỉ có sau khi seed); thông số bỏ trống ⇒ copy từ bài như thường. */
